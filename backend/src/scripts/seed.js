async function main() {
  const zeroStats = process.argv.includes('--zero-stats')
  const categoryIds = new Map()
  for (const [categoryName, description] of categories) {
    const category = await prisma.category.upsert({ where: { categoryName }, create: { categoryName, description }, update: { description } })
    categoryIds.set(categoryName, category.categoryId)
  }

  // Clean up old short titles that were renamed/expanded so there are no duplicate guides.
  const replacedTitles = [
    'ฉบับร่าง: การสำรองข้อมูลไฟล์งานประจำสัปดาห์',
    'การตั้งค่า IP และ DNS บน Windows 11',
    'ตรวจสอบคอมพิวเตอร์ทำงานช้าก่อนแจ้งซ่อม',
    'แนวทางแก้ไขเมื่อเชื่อมต่อ Wi-Fi ไม่ได้',
    'ตรวจสอบเมื่ออินเทอร์เน็ตใช้งานได้ช้าหรือขาดช่วง',
    'บันทึกเอกสารและกู้คืนไฟล์ฉบับก่อนหน้า',
    'ฉบับร่าง: แนวทางประชุมออนไลน์สำหรับเจ้าหน้าที่',
    'แก้ปัญหาสั่งพิมพ์ Network Printer ไม่ออก',
    'เปลี่ยนตลับหมึกและตรวจสอบคุณภาพงานพิมพ์',
    'แนวทางเมื่อเข้าใช้ระบบสารสนเทศไม่ได้',
    'ขั้นตอนขอรีเซ็ตรหัสผ่านอย่างปลอดภัย',
  ]
  await prisma.article.deleteMany({
    where: {
      title: { in: replacedTitles },
      image: null,
      pdfFile: null,
    },
  })

  for (const guide of guides) {
    const { category, intro, detail, steps, views, status = 'PUBLISHED', ...fields } = guide
    const categoryId = categoryIds.get(category)
    const effectiveViews = zeroStats ? 0 : views
    const publishedAt = status === 'PUBLISHED' ? new Date(Date.now() - (views % 45) * 86400000) : null
    const content = detail ? `เกริ่นนำ\n${intro}\n\n${detail}` : `เกริ่นนำ\n${intro}`
    const data = { ...fields, categoryId, content, steps, viewCount: effectiveViews, status, featured: Boolean(guide.featured), publishedAt }
    const existing = await prisma.article.findFirst({ where: { title: guide.title }, select: { articleId: true } })
    const article = existing
      ? await prisma.article.update({ where: { articleId: existing.articleId }, data })
      : await prisma.article.create({ data })
    if (status === 'PUBLISHED' && !zeroStats) {
      const legacySeedKeys = Array.from({ length: 5 }, (_, index) => `${String(article.articleId).padStart(8, '0')}${String(index + 1).padStart(56, '0')}`)
      await prisma.articleFeedback.deleteMany({ where: { articleId: article.articleId, voterKey: { in: legacySeedKeys } } })
      for (let index = 0; index < 5; index += 1) {
        const voterKey = createHash('sha256').update(`ict-seed:${article.articleId}:${index + 1}`).digest('hex')
        await prisma.articleFeedback.upsert({
          where: { articleId_voterKey: { articleId: article.articleId, voterKey } },
          create: { articleId: article.articleId, voterKey, helpful: index < 4 },
          update: { helpful: index < 4 },
        })
      }
      for (let daysAgo = 0; daysAgo < 30; daysAgo += 1) {
        if (daysAgo % 7 === 6) continue
        const dailyCount = ((article.articleId + daysAgo) % 4) + (guide.featured ? 2 : 0)
        const day = bangkokDayOffset(daysAgo)
        await prisma.articleViewDaily.upsert({
          where: { articleId_day: { articleId: article.articleId, day } },
          create: { articleId: article.articleId, day, count: dailyCount },
          update: { count: dailyCount },
        })
      }
    }
  }

  await prisma.siteSetting.upsert({
    where: { key: CONTACT_SETTING_KEY },
    create: { key: CONTACT_SETTING_KEY, value: defaultContact },
    update: { value: defaultContact },
  })

  if (!zeroStats) {
    await prisma.searchLog.deleteMany({ where: { term: { in: sampleSearches.map((item) => item.term) } } })
    const searchRows = sampleSearches.flatMap((item, groupIndex) =>
      Array.from({ length: item.count }, (_, index) => ({
        term: item.term,
        resultCount: item.resultCount,
        createdAt: new Date(Date.now() - ((groupIndex + index) % 21) * 86400000 - index * 3600000),
      }))
    )
    await prisma.searchLog.createMany({ data: searchRows })
  }

  console.log(`Seed complete: ${categories.length} categories, ${guides.length} articles (${zeroStats ? 'stats set to 0' : 'with presentation stats'}), and KKICT contact settings.`)
}

main().catch((error) => { console.error('Seed failed:', error); process.exitCode = 1 }).finally(async () => { await prisma.$disconnect() })
